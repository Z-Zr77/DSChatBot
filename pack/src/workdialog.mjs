export const JS = [
  'window.__wkBind = function (el, o) {',
  '  o = o || {};',
  '  const api = o.api || (async () => ({}));',
  '  const toast = o.toast || function () {};',
  '  const onDone = o.onDone || function () {};',
  "  const source = o.source || 'console';",
  '  const q = (x) => el.querySelector(x);',
  "  const say = (t, color) => { const h = q('#wkHint'); if (h) { h.textContent = t; h.style.color = color || '#7f8ea8'; } };",
  '  // 三句例子：点一下就填进「顺手让她干点什么」',
  '  const exBox = q("#wkExamples");',
  '  const EX = ' + JSON.stringify(EXAMPLES) + ';',
  '  if (exBox) {',
  '    for (const e of EX) {',
  '      const b = document.createElement("button");',
  '      b.type = "button";',
  '      b.textContent = e.text;',
  '      b.title = e.note;',
  '      b.style.cssText = "background:#151b26;border:1px solid #2a3346;color:#9fb0cc;border-radius:8px;padding:4px 10px;font-size:12px;cursor:pointer;text-align:left";',
  '      b.onclick = () => {',
  '        const f = q("#wkFirst");',
  '        if (f) { f.value = e.text; f.focus(); }',
  '        say("开始了就先把这句发给她（" + e.note + "）");',
  '      };',
  '      exBox.appendChild(b);',
  '    }',
  '  }',
  '  // 上次用过的文件夹：只做预填，不再单独长一个按钮',
  '  (async () => {',
  '    try {',
  '      const w = await api("/api/work");',
  '      const last = (w && w.lastRoot) || "";',
  '      const inp = q("#wkRoot");',
  '      if (last && inp && !inp.value) { inp.value = last; say("已经填上上次用的文件夹，直接点「开始工作」。"); }',
  '    } catch (e) {}',
  '  })();',
  "  let __pickCur = ''; let __pickParent = '';",
  "  const paintRow = (box, text, color, onClick) => {",
  "    const d = document.createElement('div');",
  "    d.textContent = text;",
  "    d.style.cssText = 'padding:6px 10px;font-size:12.5px;color:' + color + ';cursor:pointer;border-bottom:1px solid #161d28';",
  '    if (onClick) d.onclick = onClick;',
  '    box.appendChild(d);',
  '  };',
  '  const loadDirs = async (p2) => {',
  "    const list = q('#wkPickList'), pp = q('#wkPickPath');",
  '    if (!list) return;',
  "    list.innerHTML = '';",
  "    paintRow(list, '读目录里…', '#8b98ad', null);",
  '    try {',
  "      const r = await api('/api/work/dirs?path=' + encodeURIComponent(p2 || ''));",
  "      list.innerHTML = '';",
  "      if (!r || !r.ok) { paintRow(list, (r && r.err) || '读不了这个目录', '#f0666e', null); return; }",
  '      __pickCur = r.path; __pickParent = r.parent || "";',
  '      if (pp) { pp.textContent = r.path; pp.title = r.path; }',
  '      const ds = r.dirs || [];',
  "      if (!ds.length) paintRow(list, '这里没有子文件夹（可以就用这个）', '#8b98ad', null);",
  "      for (const d of ds) paintRow(list, '📁 ' + d.name, '#cfd8e6', () => loadDirs(d.path));",
  "    } catch (e) { list.innerHTML = ''; paintRow(list, String(e.message || e), '#f0666e', null); }",
  '  };',
  // 浏览：先叫主程序弹 Windows 原生的「选择文件夹」（能自由跳盘、新建文件夹）；
  // 主程序没在跑（例如用浏览器打开控制台）才退回页面内列表。取消原生框就什么都不做。
  "  if (q('#wkBrowse')) q('#wkBrowse').onclick = async () => {",
  "    const cur = (q('#wkRoot') || {}).value || '';",
  '    let r = null;',
  '    try {',
  "      r = await api('/api/work/pick-dir', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ from: cur }) });",
  '    } catch (e) { r = null; }',
  "    if (r && r.ok && r.path) { q('#wkRoot').value = r.path; say('选好了：' + r.path); return; }",
  '    if (r && r.canceled) return;',
  '    // 原生框用不了：退回页面内列表',
  "    const box = q('#wkPicker');",
  '    if (!box) return;',
  "    box.style.display = 'block';",
  "    loadDirs(cur);",
  '  };',
  "  if (q('#wkPickCancel')) q('#wkPickCancel').onclick = () => { q('#wkPicker').style.display = 'none'; };",
  "  if (q('#wkPickOk')) q('#wkPickOk').onclick = () => {",
  '    if (!__pickCur) return;',
  "    q('#wkRoot').value = __pickCur;",
  "    q('#wkPicker').style.display = 'none';",
  "    say('选好了：' + __pickCur);",
  '  };',
  "  const goBtns = el.querySelectorAll('#wkPicker [data-go]');",
  '  for (const b2 of goBtns) {',
  '    b2.onclick = () => {',
  '      const k = b2.getAttribute("data-go");',
  '      if (k === "home") return loadDirs("");',
  '      if (k === "up") return loadDirs(__pickParent || "");',
  '    };',
  '  }',
  "  if (q('#wkNo')) q('#wkNo').onclick = () => { el.remove(); };",
  "  q('#wkYes').onclick = async () => {",
  "    const root = q('#wkRoot').value.trim();",
  "    if (!root) { q('#wkErr').textContent = '先选一个文件夹'; return; }",
  "    if (!/^([A-Za-z]:[\\\\/]|[\\\\/]{2})/.test(root)) { q('#wkErr').textContent = '要填绝对路径（例如 E:/work/周报）'; return; }",
  "    q('#wkErr').textContent = '';",
  "    q('#wkYes').disabled = true;",
  "    const r = await api('/api/work/start', {",
  "      method: 'POST', headers: { 'content-type': 'application/json' },",
  '      body: JSON.stringify({',
  '        root,',
  "        caps: [ 'fs:read', 'fs:write', 'exec' ],",
  '        useExisting: true, confirmWrite: true, source,',
  '      }),',
  '    });',
  "    q('#wkYes').disabled = false;",
  "    if (!r || r.ok === false) { q('#wkErr').textContent = (r && r.err) || '开不了'; return; }",
  '    const real = (r.state && r.state.root) || root;',
  '    const first = (q("#wkFirst").value || "").trim();',
  '    el.remove();',
  '    toast("工作区：" + real);',
  '    onDone(r);',
  '    if (first) {',
  '      try {',
  '        await api("/api/chat/send", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ text: first }) });',
  '        toast("已经发给她了：" + first.slice(0, 20) + (first.length > 20 ? "…" : ""));',
  '      } catch (e) { toast("发不出去：" + (e.message || e)); }',
  '    }',
  '  };',
  '};',
].join('\n');

export function bootstrap() {
  return 'window.__WK_INNER = ' + JSON.stringify(INNER) + ';\n' + JS;
}
